/** 界面语言：zh / en / ja */
let LANG = "zh";
/** windows / macos，设置页加载时由后端告知 */
let PLATFORM = "windows";

function t(key, vars) {
  const platform = PLATFORM === "macos" ? I18N_MACOS[LANG][key] ?? I18N_MACOS.en[key] : undefined;
  let s = platform ?? I18N[LANG][key] ?? I18N.en[key] ?? key;
  for (const [k, v] of Object.entries(vars ?? {})) s = s.replaceAll(`{${k}}`, v);
  return s;
}

/** 设置语言（zh / en / ja）并刷新所有标注过的文字 */
function applyI18n(lang) {
  LANG = I18N[lang] ? lang : "zh";
  document.documentElement.lang = { zh: "zh-CN", en: "en", ja: "ja" }[LANG];
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  document.querySelectorAll("[data-i18n-title]").forEach((el) => (el.title = t(el.dataset.i18nTitle)));
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
}
